'use strict';
// Builds the offline release: one self-contained HTML file plus the data and documentation.
// Run with `npm run build`.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..'), dist = path.join(root, 'dist');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
fs.mkdirSync(dist, { recursive: true });

// The classic-script mirror of the lesson data is always regenerated from the editable JSON.
let lessons = [];
if (fs.existsSync(path.join(root, 'data/puzzles.json'))) {
  lessons = JSON.parse(read('data/puzzles.json'));
  fs.writeFileSync(path.join(root, 'data/puzzles.js'), 'globalThis.Coach=globalThis.Coach||{};globalThis.Coach.puzzles=' + JSON.stringify(lessons, null, 2) + ';\n');
}

// A readable catalogue of the course, kept in step with the data.
if (lessons.length) {
  const tactics = { control: 'Touch & control', hide: 'Hide behind a colour', escape: 'Escape with cushions', object: 'Move the red', break: 'Break-off' };
  const levels = ['Beginner', 'Foundation', 'Intermediate', 'Advanced', 'Challenge'];
  let md = '# Puzzle library\n\nThis file is generated by `npm run build` from `data/puzzles.json`. Every reference shot was produced by the shared physics engine and independently re-simulated by the test suite.\n';
  lessons.forEach((p, i) => { p.number = i + 1; });
  for (let level = 1; level <= 5; level++) {
    const group = lessons.filter(p => p.level === level);
    md += `\n## Level ${level} · ${levels[level - 1]}\n\n| # | Puzzle | Tactic | What you will learn | Notes |\n|---|---|---|---|---|\n`;
    for (const p of group) md += `| ${p.number} | ${p.title} | ${tactics[p.tactic]} | ${p.learn} | ${[...p.tags].join(', ') || '–'} |\n`;
  }
  md += `\n${lessons.length} puzzles in total. Learners can add up to 50 of their own on the Create screen.\n`;
  fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
  fs.writeFileSync(path.join(root, 'docs/puzzle-library.md'), md);
}

// Inline the stylesheet and every script so the HTML file needs nothing else.
let html = read('index.html');
html = html.replace('<link rel="stylesheet" href="styles.css">', () => '<style>' + read('styles.css') + '</style>');
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, file) => '<script>\n' + read(file).replace(/<\/script/gi, '<\\/script') + '\n</script>');
fs.writeFileSync(path.join(dist, 'Snooker-Safety-Coach.html'), html);
fs.writeFileSync(path.join(dist, 'index.html'), html);

for (const dir of ['data', 'docs']) if (fs.existsSync(path.join(root, dir))) fs.cpSync(path.join(root, dir), path.join(dist, dir), { recursive: true });
for (const file of ['README.md', 'CHANGELOG.md', 'DESIGN_BRIEF.md']) if (fs.existsSync(path.join(root, file))) fs.copyFileSync(path.join(root, file), path.join(dist, file));
console.log('Offline build: ' + path.join(dist, 'Snooker-Safety-Coach.html') + ' (' + Math.round(html.length / 1024) + ' KB)');
