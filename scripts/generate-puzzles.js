const R = P.TABLE.radius;
const ball = (id, color, x, y) => ({ id, color, x, y });
const shot = (angle, cueSpeed, top = 0, side = 0) => ({ angle, cueSpeed, top, side });
const simulate = (balls, s) => P.simulate(balls, s, P.DEFAULTS, { recordFrames: false });
const inZone = (b, zone) => !zone || G.distance(b, zone) <= zone.radius + 1e-9;
const isInside = b => b.x >= R && b.x <= P.TABLE.width - R && b.y >= R && b.y <= P.TABLE.height - R;
const simple = b => ({ id: b.id, color: b.color, x: b.x, y: b.y });
const minPocket = b => Math.min(...P.TABLE.pockets.map(p => G.distance(b, p)));
const noPots = result => result.completed && !result.balls.some(b => b.potted);
// Sources are listed explicitly for each lesson.

function firstCueContact(result) {
  return result.events.find(e => e.type === 'ball' && e.ids.includes('cue'));
}
function beforeContact(result) {
  const first = firstCueContact(result);
  return result.events.filter(e => e.type === 'cushion' && e.id === 'cue' && first && e.t < first.t - 1e-9);
}
function validLayout(balls) {
  return balls.every(isInside) && balls.every((a, i) => balls.slice(i + 1).every(b => G.distance(a, b) >= 2 * R - 1e-9));
}
function clearOfTracks(blocker, result, clearance = 2 * R + .012) {
  return Object.values(result.tracks).every(track => {
    for (let i = 1; i < track.length; i++) {
      if (G.pointSegmentDistance(blocker, track[i - 1], track[i]) < clearance) return false;
    }
    return true;
  });
}

// Build a genuine escape: the cue path is generated by physics, then a red is
// placed after cushion n. All balls are then re-simulated; a colour blocks the
// original direct line while remaining clear of every actual moving-ball track.
function constructEscape(spec) {
  for (const seed of spec.seeds) {
    const cue = ball('cue', 'white', seed.x, seed.y);
    const s = shot(seed.angle, seed.speed, seed.top || 0, seed.side || 0);
    const free = simulate([cue], s);
    const rails = free.events.filter(e => e.type === 'cushion');
    if (rails.length < spec.preCushions || !noPots(free)) continue;
    const from = rails[spec.preCushions - 1].t;
    const until = rails[spec.preCushions]?.t || free.duration;
    for (const fraction of [.35, .5, .2, .65, .8]) {
      const time = from + (until - from) * fraction;
      const i = free.path.findIndex((p, j) => j > 0 && p.t >= time);
      if (i < 1 || i >= free.path.length - 1) continue;
      const q = free.path[i], prev = free.path[i - 1];
      const a = Math.atan2(q.y - prev.y, q.x - prev.x);
      const target = ball('red1', 'red', q.x + 2 * R * Math.cos(a), q.y + 2 * R * Math.sin(a));
      if (!validLayout([cue, target])) continue;
      const twoBall = simulate([cue, target], s);
      if (!noPots(twoBall) || !firstCueContact(twoBall) || beforeContact(twoBall).length !== spec.preCushions) continue;
      if (!inZone(twoBall.balls[0], spec.constructionCueZone || spec.objective.cueZone)) continue;
      for (const f of [.45, .6, .3, .75, .2, .85]) {
        const blocker = ball(spec.colour || 'blue', spec.colour || 'blue', cue.x + f * (target.x - cue.x), cue.y + f * (target.y - cue.y));
        if (!validLayout([cue, target, blocker]) || !clearOfTracks(blocker, twoBall)) continue;
        const balls = [cue, target, blocker];
        const result = simulate(balls, s);
        const first = firstCueContact(result);
        if (!noPots(result) || !first?.ids.includes('red1') || beforeContact(result).length !== spec.preCushions) continue;
        if (!inZone(result.balls[0], spec.constructionCueZone || spec.objective.cueZone)) continue;
        const view = G.occlusion(cue, target, [blocker]);
        if (!view.valid || view.blockedFraction < .99) continue;
        return { balls, referenceShot: s, construction: { method: 'forward-path-then-recheck-all-balls', seed, fraction, blockerFraction: f } };
      }
    }
  }
  throw new Error('No verified escape found: ' + spec.id);
}

// Put a stationary colour in a verified gap between the two outgoing tracks.
// Rigid transformation puts the chosen colour on its official spot. The whole
// transformed, three-ball position is independently simulated again.
function constructHide(spec) {
  const initial = [ball('cue', 'white', 1.1, .9), ball('red1', 'red', 1.55, .9)];
  const baseShot = shot(spec.cut, spec.speed);
  const base = simulate(initial, baseShot);
  const c = base.balls[0], t = base.balls[1], d = G.distance(c, t);
  const blocker = ball(spec.colour, spec.colour, c.x + .15 * (t.x - c.x) / d, c.y + .15 * (t.y - c.y) / d);
  assert.ok(clearOfTracks(blocker, base), spec.id + ': colour crosses trajectory');
  const a = spec.rotation * Math.PI / 180;
  const transform = b => {
    const dx = b.x - blocker.x, dy = b.y - blocker.y;
    return { ...b, x: spec.spot.x + dx * Math.cos(a) - dy * Math.sin(a), y: spec.spot.y + dx * Math.sin(a) + dy * Math.cos(a) };
  };
  const balls = [...initial, blocker].map(transform);
  assert.ok(validLayout(balls), spec.id + ': invalid transformed layout');
  return { balls, referenceShot: { ...baseShot, angle: baseShot.angle + spec.rotation },
    construction: { method: 'verified-track-clear-colour-on-official-spot', baseShot, rotation: spec.rotation } };
}

