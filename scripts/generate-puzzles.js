function makeProof(puzzle, result) {
  const first = firstCueContact(result), cue = result.balls.find(b => b.id === 'cue');
  const target = result.balls.find(b => b.id === puzzle.targetId);
  const targets = puzzle.legalTargetIds || [puzzle.targetId];
  const blockers = puzzle.balls.filter(b => b.id !== 'cue' && !targets.includes(b.id));
  const initialView = G.occlusion(puzzle.balls.find(b => b.id === 'cue'), puzzle.balls.find(b => b.id === puzzle.targetId), blockers);
  const metrics = S.outcomeMetrics(puzzle, result.balls, { verified: true });
  const firstId = first?.ids.find(id => id !== 'cue');
  const targetStart = puzzle.balls.find(b => b.id === puzzle.targetId);
  return { engine:'src/physics.js', dt:P.DT, completed:result.completed, firstContactId:firstId,
    legalFirstContact:targets.includes(firstId), preContactCushions:beforeContact(result).map(e => e.wall),
    allCueCushions:result.events.filter(e => e.type === 'cushion' && e.id === 'cue').map(e => e.wall),
    pockets:result.events.filter(e => e.type === 'pocket').map(e => ({ id:e.id,pocket:e.pocket })),
    initialBlockedFraction:initialView.blockedFraction, initialScreened:initialView.blockedFraction >= .99,
    finalDeltaDegrees:metrics.deltaDegrees, finalBlockedFraction:metrics.blockedFraction, finalExposure:metrics.exposure,
    cueRailDistance:metrics.cueRailDistance, cueZoneReached:inZone(cue,puzzle.objective.cueZone),
    targetZoneReached:inZone(target,puzzle.objective.targetZone), separation:G.distance(cue,target),
    targetTravel:G.distance(target,targetStart), targetPocketDistance:minPocket(target),
    pocketDistanceGain:minPocket(target)-minPocket(targetStart),
    cueInBaulk:cue.x<=P.TABLE.baulk,
    redTotalTravel:result.balls.filter(b=>b.color==='red').reduce((sum,b)=>sum+G.distance(b,puzzle.balls.find(old=>old.id===b.id)),0) };
}

function verify(puzzle, result) {
  assert.ok(validLayout(puzzle.balls), puzzle.id + ': initial balls overlap or leave table');
  const legal = S.checkResult(puzzle,result);
  assert.ok(legal.valid, puzzle.id + ': ' + legal.reason);
  const proof = makeProof(puzzle,result), a = puzzle.acceptance || {};
  assert.ok(proof.cueZoneReached && proof.targetZoneReached, puzzle.id + ': declared zone missed');
  if(a.preContactCushions!==undefined) assert.equal(proof.preContactCushions.length,a.preContactCushions,puzzle.id+': wrong pre-contact rails');
  if(a.cueCushions!==undefined) assert.equal(proof.allCueCushions.length,a.cueCushions,puzzle.id+': wrong rail count');
  for(const [field,min] of Object.entries({initialBlockedFraction:a.initialBlockedFraction,finalBlockedFraction:a.minBlockedFraction,separation:a.minSeparation,targetPocketDistance:a.minTargetPocketDistance,pocketDistanceGain:a.minPocketDistanceGain})) {
    if(min!==undefined) assert.ok(proof[field]>=min-1e-9,puzzle.id+': '+field+' '+proof[field]+' < '+min);
  }
  for(const [field,max] of Object.entries({cueRailDistance:a.maxCueRailDistance,targetTravel:a.maxTargetTravel,redTotalTravel:a.maxRedTotalTravel})) {
    if(max!==undefined) assert.ok(proof[field]<=max+1e-9,puzzle.id+': '+field+' '+proof[field]+' > '+max);
  }
  if(a.cueBaulk) assert.ok(proof.cueInBaulk,puzzle.id+': cue outside baulk');
  if(a.fullRack) {
    assert.equal(puzzle.balls.length,22); assert.equal(puzzle.balls.filter(b=>b.color==='red').length,15);
    const c=puzzle.balls.find(b=>b.id==='cue');assert.ok(c.x<=P.TABLE.baulk&&Math.hypot(c.x-P.TABLE.baulk,c.y-P.TABLE.height/2)<=P.TABLE.dRadius);
    for(const colour of ['yellow','green','brown','blue','pink','black'])assert.equal(puzzle.balls.filter(b=>b.color===colour).length,1);
  }
  return proof;
}

function generate() {
  const output=[], references={version:1,generatedWith:'src/physics.js; fixed 1 ms; default parameters',references:{}};
  for(const original of specs()) {
    const spec={...original};
    if(spec.preCushions){Object.assign(spec,constructEscape(spec));if(spec.polishedShot){spec.referenceShot=spec.polishedShot;spec.construction.refinement='bounded angle/speed/top search improved separation and rail position; selected shot independently verified';}}
    else if(spec.spot)Object.assign(spec,constructHide(spec));
    else if(spec.id==='break-off') {
      const saved=breakoffFixture();
      spec.balls=saved.balls.map(simple);spec.referenceShot=saved.referenceShot;
      spec.legalTargetIds=spec.balls.filter(b=>b.color==='red').map(b=>b.id);
      spec.construction={method:'bounded full-rack search followed by independent forward verification',globalOptimality:false};
    }
    for(const key of ['seeds','preCushions','colour','cut','speed','rotation','spot','constructionCueZone','polishedShot'])delete spec[key];
    spec.legalTargetIds=spec.legalTargetIds||[spec.targetId];
    const result=simulate(spec.balls,spec.referenceShot);
    spec.proof=verify(spec,result);
    output.push(spec);
    const {frames,...record}=result;
    references.references[spec.id]=record;
    console.log(`${spec.id}: first ${spec.proof.firstContactId}; pre-rails ${spec.proof.preContactCushions.join('>')||'0'}; final hide ${(spec.proof.finalBlockedFraction*100).toFixed(1)}%; ${result.duration.toFixed(3)} s`);
  }
  fs.mkdirSync(path.join(ROOT,'data'),{recursive:true});
  fs.writeFileSync(path.join(ROOT,'data','puzzles.json'),JSON.stringify(output,null,2)+'\n');
  fs.writeFileSync(path.join(ROOT,'data','references.json'),JSON.stringify(references)+'\n');
  fs.writeFileSync(path.join(ROOT,'data','puzzles.js'),'/* Generated from puzzles.json by scripts/generate-puzzles.js. */\n(function(root){root.Coach=root.Coach||{};root.Coach.puzzles='+JSON.stringify(output)+';})(globalThis);\n');
  console.log(`Verified ${output.length} lessons and saved independent JSON + offline classic-script mirror.`);
  return {puzzles:output,references};
}
